let selectedCategory = "all";

function getFurnitureProducts() {
    return Object.entries(furniture_details).flatMap(([category, subcategories]) =>
        Object.entries(subcategories).flatMap(([subcategory, products]) =>
            Object.entries(products).map(([productKey, product]) => ({
                ...product,
                category,
                subcategory,
                id: `${category}-${subcategory}-${productKey}`
            }))
        )
    );
}

// The homepage reuses this catalog without duplicating product data.
window.furniture_details = furniture_details;
window.getFurnitureProducts = getFurnitureProducts;

function renderFurniture() {
    const furnitureContainer = document.getElementById("furniture");
    const productCount = document.getElementById("product-count");
    const sortSelect = document.getElementById("sort-furniture");

    if (!furnitureContainer) {
        return;
    }

    let products = getFurnitureProducts();

    if (selectedCategory !== "all") {
        products = products.filter((product) => product.category === selectedCategory);
    }

    if (sortSelect) {
        if (sortSelect.value === "price-low") {
            products.sort((first, second) => first.price - second.price);
        } else if (sortSelect.value === "price-high") {
            products.sort((first, second) => second.price - first.price);
        } else if (sortSelect.value === "rating") {
            products.sort((first, second) => second.rating - first.rating);
        }
    }

    furnitureContainer.replaceChildren();
    let i=1;
    products.forEach((product) => {
        const card = document.createElement("article");
        card.className = "furniture-card";
        card.dataset.id = product.id;

        const image = document.createElement("img");
        image.src = product.image;
        image.alt = product.name;
        image.className = "product-image";

        const details = document.createElement("div");
        details.className = "furniture-details";

        const category = document.createElement("p");
        category.className = "product-category";
        category.textContent = product.category;

        const name = document.createElement("h3");
        name.textContent = product.name;

        const price = document.createElement("p");
        price.className = "product-price";
        price.textContent = `₹${product.price.toLocaleString("en-IN")}`;

        const rating = document.createElement("p");
        rating.className = "product-rating";
        rating.textContent = `★ ${product.rating}`;

        const material = document.createElement("p");
        material.textContent = `Material: ${product.material}`;

        details.append(category, name, price, rating, material);
        card.append(image, details);
        furnitureContainer.appendChild(card);
    });

    if (productCount) {
        productCount.textContent = `${products.length} ${products.length === 1 ? "product" : "products"}`;
    }
}

document.querySelectorAll(".category-button").forEach((button) => {
    button.addEventListener("click", () => {
        document.querySelectorAll(".category-button").forEach((item) => item.classList.remove("active"));
        button.classList.add("active");
        selectedCategory = button.dataset.category;
        renderFurniture();
    });
});

const sortFurniture = document.getElementById("sort-furniture");
if (sortFurniture) {
    sortFurniture.addEventListener("change", renderFurniture);
}

renderFurniture();

const furnitureContainer = document.getElementById("furniture");

if (furnitureContainer) {
furnitureContainer.addEventListener("click", (event) => {
 const card = event.target.closest(".furniture-card");

    if (!card) {
        return;
    }

    const furnitureId = card.dataset.id;
    const category = furnitureId.split("-")[0];
    const product = getFurnitureProducts().find((item) => item.id === furnitureId);

    if (product) {
        sessionStorage.setItem("selectedFurniture", JSON.stringify(product));
    }

    window.location.href =
        `../furniture_details/${category}/index.html?id=${encodeURIComponent(furnitureId)}`;
});
}
